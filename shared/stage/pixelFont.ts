const GLYPH: Record<string, number[]> = {}
for (const [char, rows] of Object.entries(RAW)) {
  GLYPH[char] = rows.map(row => Number.parseInt(row, 2))
}

const ADVANCE = 6
const LINE = 9

export function wrapPixel(text: string, maxCols: number) {
  const words = text.toUpperCase().split(/\s+/).filter(Boolean)
  const lines: string[] = []
  let line = ''
  for (const word of words) {
    const next = line ? `${line} ${word}` : word
    if (line && next.length > maxCols) {
      lines.push(line)
      line = word
    } else {
      line = next
    }
  }
  if (line) lines.push(line)
  return lines.length ? lines : ['']
}

export function measurePixel(lines: string[], scale: number) {
  const cols = Math.max(1, ...lines.map(line => Math.max(1, line.length) * ADVANCE))
  return {
    width: cols * scale + scale,
    height: Math.max(1, lines.length) * LINE * scale + scale,
  }
}

export function drawPixel(
  ctx: CanvasRenderingContext2D,
  lines: string[],
  originX: number,
  originY: number,
  scale: number,
  color: string,
) {
  for (let pass = 0; pass < 2; pass++) {
    ctx.fillStyle = pass === 0 ? '#14080c' : color
    const drop = pass === 0 ? scale : 0
    lines.forEach((line, lineIndex) => {
      for (let index = 0; index < line.length; index++) {
        const glyph = GLYPH[line[index]!]
        if (!glyph) continue
        const left = originX + drop + index * ADVANCE * scale
        const top = originY + drop + lineIndex * LINE * scale
        for (let row = 0; row < glyph.length; row++) {
          const bits = glyph[row]!
          for (let col = 0; col < 5; col++) {
            if (bits & (1 << (4 - col))) {
              ctx.fillRect(left + col * scale, top + row * scale, scale, scale)
            }
          }
        }
      }
    })
  }
}
